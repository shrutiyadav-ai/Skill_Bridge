  console.log(`📚 Seeding ${ONLINE_COURSES_SEED.length} verified Online Courses...`);

  for (const course of ONLINE_COURSES_SEED) {
    await prisma.onlineCourse.upsert({
      where: { id: "00000000-0000-0000-0000-" + Buffer.from(course.title).toString("hex").slice(0, 12).padStart(12, "0") },
      update: {
        title: course.title,
        platform: course.platform,
        provider: course.provider,
        url: course.url,
        skillsCovered: course.skillsCovered,
        category: course.category,
        difficulty: course.difficulty,
        duration: course.duration,
        certificationAvailable: course.certificationAvailable,
        isFree: course.isFree,
        pricingType: course.pricingType,
        rating: course.rating,
        enrolledCount: course.enrolledCount,
        description: course.description,
        courses: course.courses,
        departments: course.departments,
        isActive: true,
      },
      create: {
        id: "00000000-0000-0000-0000-" + Buffer.from(course.title).toString("hex").slice(0, 12).padStart(12, "0"),
        title: course.title,
        platform: course.platform,
        provider: course.provider,
        url: course.url,
        skillsCovered: course.skillsCovered,
        category: course.category,
        difficulty: course.difficulty,
        duration: course.duration,
        certificationAvailable: course.certificationAvailable,
        isFree: course.isFree,
        pricingType: course.pricingType,
        rating: course.rating,
        enrolledCount: course.enrolledCount,
        description: course.description,
        courses: course.courses,
        departments: course.departments,
        isActive: true,
      },
    });
  }

  console.log(`✅ Successfully seeded ${ONLINE_COURSES_SEED.length} authentic online courses into Supabase!`);
